"""Synthesized video and audio fixtures, built on the machine, from nothing.

No asset ships with this repository and none is downloaded. Every fixture
here is generated by `ffmpeg` (and, for frames that must genuinely differ,
Pillow) into a caller-supplied temporary path, so the suite proves the real
subprocess paths work rather than mocking their shape -- the same posture
`evidence_fakes.py`'s `make_text_pdf` takes for documents.

Two notes on what is *not* used:

* **`drawtext` is unavailable.** This machine's ffmpeg is built without
  libfreetype, so on-screen text is rendered into a PNG with Pillow and then
  encoded as a still video (`-loop 1 -tune stillimage`). That also makes the
  text exact and independent of a font ffmpeg happens to bundle.
* **Speech comes from macOS `say`.** `say -o clip.aiff "..."` is the only
  offline speech synthesizer guaranteed present on the target platform. Any
  test depending on it skips cleanly elsewhere.

Every function writes only to the path it is given (and, where it needs one,
a directory it creates beneath that path's parent), which the callers always
place inside a `tempfile.TemporaryDirectory`. Nothing here touches the
owner's files, the Angel volume, or the repository.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

FFMPEG_TIMEOUT_SECONDS = 120


def ffmpeg_available() -> bool:
    return shutil.which("ffmpeg") is not None


def say_available() -> bool:
    return shutil.which("say") is not None


def _run(command: list[str]) -> None:
    subprocess.run(command, check=True, timeout=FFMPEG_TIMEOUT_SECONDS, capture_output=True)


# -- images -------------------------------------------------------------------


def write_text_png(path: Path, text: str, *, size: tuple[int, int] = (640, 360)) -> Path:
    """A PNG carrying `text` in large black letters on white, for OCR.

    Pillow rather than ffmpeg's `drawtext`, which this machine's build does
    not have. A real TrueType face is used when one is present because
    Pillow's built-in bitmap font is too small for tesseract to read
    reliably; the fallback keeps the fixture working on a machine without it.
    """
    from PIL import Image, ImageDraw, ImageFont

    image = Image.new("RGB", size, (255, 255, 255))
    draw = ImageDraw.Draw(image)
    font = None
    for candidate in (
        "/System/Library/Fonts/Supplemental/Arial.ttf",
        "/System/Library/Fonts/Helvetica.ttc",
        "/Library/Fonts/Arial.ttf",
    ):
        try:
            font = ImageFont.truetype(candidate, 44)
            break
        except OSError:
            continue
    if font is None:
        font = ImageFont.load_default()
    draw.multiline_text((30, 100), text, fill=(0, 0, 0), font=font, spacing=16)
    image.save(path, format="PNG")
    return path


def write_distinct_png(
    path: Path, index: int, *, size: tuple[int, int] = (320, 240)
) -> Path:
    """One of a family of pictures that are genuinely distinct to a hash.

    Each frame is `index + 1` black bars on white, at a shifting offset. That
    changes both the mean brightness and the *position* of the bits in an 8x8
    average hash -- which matters, because a family that merely alternates
    between two looks (dark frame, light frame, dark frame, ...) is correctly
    de-duplicated down to two representatives and would make a test claiming
    "five distinct frames" fail for the right reason.
    """
    from PIL import Image, ImageDraw

    width, height = size
    image = Image.new("RGB", size, (255, 255, 255))
    draw = ImageDraw.Draw(image)
    bars = index + 1
    bar_width = max(4, width // (bars * 3))
    for bar in range(bars):
        x0 = int((bar + 0.5) * width / bars) - bar_width // 2
        draw.rectangle((x0, 0, x0 + bar_width, height), fill=(0, 0, 0))
    # A horizontal band whose vertical position advances with the index, so
    # two frames with the same bar count (there are none, but a caller may
    # ask for more frames than the family has shapes) still differ.
    band_top = int((index % 5) * height / 6)
    draw.rectangle((0, band_top, width, band_top + max(6, height // 12)), fill=(0, 0, 0))
    image.save(path, format="PNG")
    return path


def _write_flat_png(path: Path, color: tuple[int, int, int], size: tuple[int, int]) -> Path:
    """One featureless picture, for the deliberately-static fixture."""
    from PIL import Image, ImageDraw

    image = Image.new("RGB", size, color)
    draw = ImageDraw.Draw(image)
    inverse = tuple(255 - channel for channel in color)
    draw.rectangle((0, 0, size[0] // 2, size[1]), fill=inverse)
    image.save(path, format="PNG")
    return path


# -- video --------------------------------------------------------------------


def make_test_pattern_video(path: Path, *, duration: float = 2.0, size: str = "64x64") -> Path:
    """ffmpeg's own `testsrc` chart. Cheap, and near-static to a perceptual hash."""
    _run([
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-f", "lavfi", "-i", f"testsrc=duration={duration}:size={size}:rate=5",
        str(path),
    ])
    return path


def make_static_video(path: Path, *, duration: float = 6.0, size: tuple[int, int] = (320, 240)) -> Path:
    """One image, held for `duration` seconds: every sampled frame identical."""
    still = path.parent / f"{path.stem}-still.png"
    _write_flat_png(still, (90, 120, 160), size)
    _run([
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-loop", "1", "-i", str(still), "-t", f"{duration}",
        "-c:v", "libx264", "-tune", "stillimage", "-pix_fmt", "yuv420p", "-r", "5",
        str(path),
    ])
    return path


def make_changing_video(
    path: Path, *, frames: int = 6, size: tuple[int, int] = (320, 240), fps: int = 1
) -> Path:
    """A clip of `frames` visibly different one-second shots.

    Used wherever a test needs deduplication *not* to fire, so that an
    assertion about sampling or per-frame backend calls measures what it
    claims to. One second per shot means the sampled timestamps land inside
    different shots for any frame count up to `frames`.
    """
    stills = path.parent / f"{path.stem}-frames"
    stills.mkdir(parents=True, exist_ok=True)
    for index in range(frames):
        write_distinct_png(stills / f"frame{index:03d}.png", index, size=size)
    _run([
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-framerate", f"{fps}", "-i", str(stills / "frame%03d.png"),
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-r", "5",
        str(path),
    ])
    return path


def make_text_video(
    path: Path,
    text: str,
    *,
    duration: float = 3.0,
    audio: Path | None = None,
    tone: bool = False,
) -> Path:
    """A still video showing `text`, for the OCR-on-a-frame path.

    `audio` mixes in a real track (see `make_speech_aiff`), which is how the
    "a video that both shows and says something" fixture is built when macOS
    `say` is available. `tone` adds a synthesized sine instead, for a test
    that needs the file to *have* an audible audio stream but does not care
    what is in it -- a fake transcription backend supplies the words.
    """
    still = path.parent / f"{path.stem}-text.png"
    write_text_png(still, text)
    command = [
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-loop", "1", "-i", str(still),
    ]
    if audio is not None:
        command += ["-i", str(audio), "-c:a", "aac", "-b:a", "64k", "-shortest"]
    elif tone:
        command += [
            "-f", "lavfi", "-i",
            f"sine=frequency=440:duration={duration}:sample_rate=16000",
            "-c:a", "aac", "-b:a", "64k", "-shortest",
        ]
    else:
        command += ["-t", f"{duration}"]
    command += [
        "-c:v", "libx264", "-tune", "stillimage", "-pix_fmt", "yuv420p", "-r", "5",
        str(path),
    ]
    _run(command)
    return path


def make_silent_video(path: Path, *, duration: float = 3.0) -> Path:
    """A video with a real but entirely silent audio stream.

    Distinct from `make_static_video`, which has no audio stream at all: the
    two exercise different branches (`audio_present` false versus a track
    whose peak sample is below the silence floor).
    """
    _run([
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-f", "lavfi", "-i", f"testsrc=duration={duration}:size=160x120:rate=5",
        "-f", "lavfi", "-i", f"anullsrc=channel_layout=mono:sample_rate=16000:d={duration}",
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest",
        str(path),
    ])
    return path


def make_tone_video(path: Path, *, duration: float = 3.0, frequency: int = 440) -> Path:
    """A video whose audio is a pure tone: audible, but not speech."""
    _run([
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-f", "lavfi", "-i", f"testsrc=duration={duration}:size=160x120:rate=5",
        "-f", "lavfi", "-i", f"sine=frequency={frequency}:duration={duration}:sample_rate=16000",
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest",
        str(path),
    ])
    return path


def make_corrupt_video(path: Path, *, keep_bytes: int = 2_048) -> Path:
    """A real MP4 truncated mid-stream: a header, then nothing that decodes."""
    whole = path.parent / f"{path.stem}-whole.mp4"
    make_test_pattern_video(whole, duration=2.0)
    path.write_bytes(whole.read_bytes()[:keep_bytes])
    return path


# -- audio --------------------------------------------------------------------


def make_speech_aiff(path: Path, text: str) -> Path:
    """Synthesized speech via macOS `say`. Caller must check `say_available()`."""
    subprocess.run(
        ["say", "-o", str(path), text], check=True, timeout=FFMPEG_TIMEOUT_SECONDS, capture_output=True
    )
    return path


def make_speech_audio_file(path: Path, text: str) -> Path:
    """An `.m4a` of synthesized speech: the MEDIA_AUDIO fixture."""
    aiff = path.parent / f"{path.stem}.aiff"
    make_speech_aiff(aiff, text)
    _run([
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-i", str(aiff), "-c:a", "aac", "-b:a", "64k", str(path),
    ])
    return path


def make_speech_video(path: Path, text: str, *, on_screen: str | None = None) -> Path:
    """A video that *says* `text`, and optionally *shows* `on_screen`.

    The fixture behind the claim that speech and visible text are two
    separate seams: a reader of the resulting evidence can tell which of the
    two a given phrase came from.
    """
    aiff = path.parent / f"{path.stem}.aiff"
    make_speech_aiff(aiff, text)
    return make_text_video(path, on_screen if on_screen is not None else "", audio=aiff)


def make_tone_audio_file(path: Path, *, duration: float = 2.0, frequency: int = 440) -> Path:
    """An `.m4a` holding a pure tone: MEDIA_AUDIO with no speech in it."""
    _run([
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-f", "lavfi", "-i", f"sine=frequency={frequency}:duration={duration}:sample_rate=16000",
        "-c:a", "aac", "-b:a", "64k", str(path),
    ])
    return path


def make_silent_audio_file(path: Path, *, duration: float = 2.0) -> Path:
    """An `.m4a` holding digital silence."""
    _run([
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-f", "lavfi", "-i", f"anullsrc=channel_layout=mono:sample_rate=16000:d={duration}",
        "-c:a", "aac", "-b:a", "64k", "-t", f"{duration}", str(path),
    ])
    return path
